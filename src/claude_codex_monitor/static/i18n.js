window.t = function (key, ...args) {
  const lang = document.documentElement.lang === 'zh' ? 'zh' : 'en';
  const table = window.I18N[lang];
  const variant = args[0] === 1 && Object.prototype.hasOwnProperty.call(window.I18N.en, key + '.one') ? key + '.one' : key;
  const template = table[variant] ?? window.I18N.en[variant] ?? window.I18N.en[key] ?? key;
  return template.replace(/\{(\d+)\}/g, (match, i) => args[i] == null ? match : String(args[i]));
};

window.tm = function (value) {
  if (value && typeof value === 'object' && typeof value.m === 'string') {
    return window.t(value.m, ...(value.a || []).map(window.tm));
  }
  return value == null ? '' : value;
};
