"""A command that runs claude -p many times (xargs -P over chunk files) belongs to the session that ran it."""
import os
import shutil
import tempfile
import time
import unittest

from claude_codex_monitor import collect as C
from claude_codex_monitor import demo
from claude_codex_monitor import server as S
from claude_codex_monitor.config import parse_args

PROJECT = '/Users/demo/code/acme-api'


class FanoutDetection(unittest.TestCase):
    def test_xargs_runs_claude(self):
        self.assertTrue(C.mentions_claude('ls chunks/*.txt | xargs -P 4 -n 1 claude -p', '/nonexistent'))
        self.assertTrue(C.mentions_claude('cat ids | xargs -0 claude --print', '/nonexistent'))
        self.assertFalse(C.mentions_claude('ls | xargs grep "claude -p"', '/nonexistent'))

    def test_xargs_runs_a_script_that_calls_claude(self):
        with tempfile.TemporaryDirectory() as d:
            with open(os.path.join(d, 'run_one.sh'), 'w') as f:
                f.write('#!/bin/bash\nclaude -p "$(cat "$1")" > "out/$(basename "$1")"\n')
            cmd = 'cd %s && ls chunks/*.json | xargs -P 6 -n 1 ./run_one.sh; echo done' % d
            self.assertTrue(C.mentions_claude(cmd, '/somewhere/else'))

    def test_folder_a_command_runs_in(self):
        self.assertEqual(C.cmd_cwd('cd /tmp/a && ls', '/x'), '/tmp/a')
        self.assertEqual(C.cmd_cwd('cd sub && ls', '/x'), '/x/sub')
        self.assertEqual(C.cmd_cwd('ls', '/x'), '/x')

    def test_scratchpad_parent(self):
        sid = '89dfaaad-4b6a-4851-95ce-d8ecfcc248e4'
        self.assertEqual(C.scratch_parent('/private/tmp/claude-502/-Users-me-proj/%s/scratchpad' % sid), sid)
        self.assertEqual(C.scratch_parent('/private/tmp/claude-502/-Users-me-proj/%s/scratchpad/out' % sid), sid)
        self.assertIsNone(C.scratch_parent('/Users/me/proj'))


def child(cd, name, cwd, t, done):
    """A claude -p session: its prompt was generated by a script, so no text of it is in the command."""
    s = demo._Claude(cd, name, cwd)
    s.user(t, 'Find the follow-ups in chat chunk %s.' % name)
    if done:
        s.say(t + 20, '[]')
    else:
        s.tool(t + 5, 'b1', 'Read', {'file_path': cwd + '/chunk.json'})
    for r in s.rows:
        r['querySource'] = 'sdk'
    return s.save()


class FanoutGrouping(unittest.TestCase):
    def scan(self, command):
        root = tempfile.mkdtemp()
        now = time.time()
        cd, xd = demo.build(os.path.join(root, 'data'), now)
        parent = demo._Claude(cd, 'seatalk', PROJECT, 'Seatalk follow-ups')
        short = tempfile.mkdtemp(prefix='ccm-', dir='/tmp')       # the folder name Claude derives from it must stay short
        self.addCleanup(shutil.rmtree, short, True)
        scratch = os.path.join(short, PROJECT.replace('/', '-'), parent.sid, 'scratchpad')
        os.makedirs(scratch)
        parent.user(now - 600, 'Find what I need to follow up on in SeaTalk.')
        parent.tool(now - 500, 'bg1', 'Bash', {'command': command.format(scratch=scratch), 'run_in_background': True,
                                                'description': 'Run all 6 chunks in parallel'})
        parent.result(now - 500, 'bg1', 'Command running in background with ID: b1', {'backgroundTaskId': 'b1'})
        parent.say(now - 499, 'Started; I will report when it finishes.')
        parent.save()
        kids = [child(cd, 'chunk%d' % i, scratch, now - 490 + i * 30, done=i < 4) for i in range(6)]
        C.configure(cd, xd, 7)
        mon = S.Monitor(parse_args(['--claude-dir', cd, '--codex-dir', xd, '--state-dir', os.path.join(root, 'state'),
                                    '--summary', 'off', '--no-desktop']))
        mon.scan()
        rows = {r['key']: r for r in mon.snapshot['rows']}
        return rows, 'claude:' + parent.sid, ['claude:' + k.sid for k in kids], mon

    def check(self, rows, pkey, kids, mon, title, total=1):
        for k in kids:
            self.assertNotIn(k, rows)                       # not listed as sessions of their own
        self.assertEqual(rows[pkey]['progress']['total'], total)
        self.assertEqual(rows[pkey]['progress']['run'], total)
        tasks = mon.detail(pkey)['tasks']
        batch = [t for t in tasks if t.get('fanout')]
        self.assertEqual(len(batch), 1)
        t = batch[0]
        self.assertEqual(t['fanout'], {'total': 6, 'running': 2, 'failed': 0})
        self.assertEqual(t['status'], 'run')
        self.assertEqual(t['title'], title)
        self.assertEqual(t['executor']['m'], 'exec.batch')

    def test_xargs_command(self):
        cmd = 'cd {scratch} && ls chunks/*.json | xargs -P 6 -n 1 claude -p --output-format json'
        rows, pkey, kids, mon = self.scan(cmd)
        self.check(rows, pkey, kids, mon, 'Run all 6 chunks in parallel')

    def test_unrecognised_command_falls_back_to_the_scratchpad(self):
        cmd = 'cd {scratch} && python3 -I fan_out.py'      # the script is not there to read
        rows, pkey, kids, mon = self.scan(cmd)
        self.check(rows, pkey, kids, mon, {'m': 'task.scratch_batch', 'a': []}, total=2)


if __name__ == '__main__':
    unittest.main()
